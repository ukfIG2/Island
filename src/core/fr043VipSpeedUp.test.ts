import { describe, expect, it } from 'vitest';
import { applyBootstrapCommand as dispatch, createInitialBootstrapState, mvpVipSpeedUpAvailable, MVP_VIP_SPEED_UP_PROVISIONAL, type BootstrapState } from './state';
import { MVP_VIP_TYPES, MVP_VIP_PROVISIONAL_TIMING, mvpVipAttainableQualityCeiling } from './vipLayer';
import { normalizePersistedState } from '../persistence/DexieBootstrapPersistence';
describe('FR-043 core-owned Energy VIP Speed Up', () => {
 it.each(MVP_VIP_TYPES)('%s accelerates only the active VIP, spending shared Energy', vipType => {
  const initial = createInitialBootstrapState('fr043-' + vipType, undefined, 'mvp');
  const running = dispatch(initial, { type: 'BEGIN_VIP_VISIT', vipType });
  const funded: BootstrapState = { ...running, energy: MVP_VIP_SPEED_UP_PROVISIONAL.energyCost };
  expect(mvpVipSpeedUpAvailable(funded)).toBe(true);
  const next = dispatch(funded, { type: 'VIP_SPEED_UP' });
  expect(next.energy).toBe(0);
  expect(next.vipLayer.active?.elapsedMs).toBe(MVP_VIP_SPEED_UP_PROVISIONAL.advanceMs);
  expect(next.vipLayer.active?.type).toBe(vipType);
  expect(next.vipLayer.active?.preparedness).toEqual(running.vipLayer.active?.preparedness);
  expect(next.normalWave).toEqual(funded.normalWave);
  expect(next.simulationTick).toBe(funded.simulationTick);
  expect(next.elapsedSimulationMs).toBe(funded.elapsedSimulationMs);
  expect(next.coins).toBe(funded.coins);
  expect(next.materials).toBe(funded.materials);
  expect(next.purchasedAreas).toEqual(funded.purchasedAreas);
  expect(mvpVipSpeedUpAvailable(next)).toBe(false);
  expect(() => dispatch(next, { type: 'VIP_SPEED_UP' })).toThrow('MVP_VIP_SPEED_UP_ENERGY_INSUFFICIENT');
  expect(normalizePersistedState(JSON.parse(JSON.stringify(next)) as BootstrapState).vipLayer).toEqual(next.vipLayer);
 });
 it('completes a VIP through the same bounded resolution path after spending three Energy', () => {
  const started = dispatch(createInitialBootstrapState('fr043-finish', undefined, 'mvp'), { type: 'BEGIN_VIP_VISIT', vipType: 'investor' });
  let state: BootstrapState = { ...started, energy: 3 };
  const preservedWave = state.normalWave;
  const ceiling = mvpVipAttainableQualityCeiling(state.vipLayer.active?.preparedness);
  for (let n = 0; n < 3; n++) state = dispatch(state, { type: 'VIP_SPEED_UP' });
  expect(state.energy).toBe(0);
  expect(state.vipLayer.active).toBeNull();
  expect(state.vipLayer.completed).toEqual(['investor']);
  expect(state.vipLayer.resolutions).toHaveLength(1);
  expect(mvpVipAttainableQualityCeiling(state.vipLayer.resolutions[0].preparedness)).toBe(ceiling);
  expect(state.normalWave).toEqual(preservedWave);
  expect(state.simulationTick).toBe(started.simulationTick);
  expect(state.elapsedSimulationMs).toBe(started.elapsedSimulationMs);
  expect(() => dispatch(state, { type: 'VIP_SPEED_UP' })).toThrow('MVP_VIP_SPEED_UP_NOT_IN_PROGRESS');
  expect(normalizePersistedState(JSON.parse(JSON.stringify(state)) as BootstrapState).vipLayer).toEqual(state.vipLayer);
 });
 it('rejects non-MVP, no active visit and insufficient Energy without state mutation', () => {
  const prototype = createInitialBootstrapState('fr043-stage', undefined, 'prototype');
  expect(mvpVipSpeedUpAvailable(prototype)).toBe(false);
  expect(() => dispatch(prototype, { type: 'VIP_SPEED_UP' })).toThrow('MVP_VIP_STAGE_INVALID');
  const idle = { ...createInitialBootstrapState('fr043-idle', undefined, 'mvp'), energy: 2 };
  expect(mvpVipSpeedUpAvailable(idle)).toBe(false);
  expect(() => dispatch(idle, { type: 'VIP_SPEED_UP' })).toThrow('MVP_VIP_SPEED_UP_NOT_IN_PROGRESS');
  const active = dispatch(createInitialBootstrapState('fr043-empty', undefined, 'mvp'), { type: 'BEGIN_VIP_VISIT', vipType: 'influencer' });
  expect(active.energy).toBe(0);
  expect(mvpVipSpeedUpAvailable(active)).toBe(false);
  expect(() => dispatch(active, { type: 'VIP_SPEED_UP' })).toThrow('MVP_VIP_SPEED_UP_ENERGY_INSUFFICIENT');
  expect(active.vipLayer.active?.elapsedMs).toBe(0);
 });
 it('preserves partial progress after hydration; final acceleration cannot overrun the normal completion boundary', () => {
  const base = dispatch(createInitialBootstrapState('fr043-persist', undefined, 'mvp'), { type: 'BEGIN_VIP_VISIT', vipType: 'weddingCouple' });
  const partially = dispatch(base, { type: 'ADVANCE_SIMULATION', deltaMs: MVP_VIP_PROVISIONAL_TIMING.visitDurationMs - 5000 });
  const restored: BootstrapState = { ...normalizePersistedState(JSON.parse(JSON.stringify(partially)) as BootstrapState), energy: 1 };
  const normalWave = restored.normalWave;
  const accelerated = dispatch(restored, { type: 'VIP_SPEED_UP' });
  expect(accelerated.vipLayer.active).toBeNull();
  expect(accelerated.vipLayer.completed).toContain('weddingCouple');
  expect(accelerated.vipLayer.resolutions).toHaveLength(1);
  expect(accelerated.energy).toBe(0);
  expect(accelerated.normalWave).toEqual(normalWave);
  expect(accelerated.elapsedSimulationMs).toBe(restored.elapsedSimulationMs);
 });
});
